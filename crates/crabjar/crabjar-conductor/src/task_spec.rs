//! Typed task specification for fleet worker deployment.
//!
//! Defines the `TaskSpec` format that supervisors use to request worker deployments
//! via `POST /workers/deploy`. Part of SUPERVISOR-DEPLOYMENT-READINESS Phase 1.

use serde::{Deserialize, Serialize};

/// Task context — what the worker needs to know about the task.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskContext {
    /// What to do and why.
    pub description: String,
    /// Target repository (pesti, crabjar, mirror-lab).
    #[serde(default)]
    pub repo: Option<String>,
    /// Specific branch to work on.
    #[serde(default)]
    pub branch: Option<String>,
    /// Relevant files or paths within the repo.
    #[serde(default)]
    pub relevant_files: Vec<String>,
    /// Constraints (deadlines, dependencies, must-not-touch).
    #[serde(default)]
    pub constraints: Vec<String>,
}

/// Expected outcome of the task.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskOutcome {
    /// What does done look like?
    pub definition_of_done: String,
    /// Deliverables (files, reports, PRs).
    #[serde(default)]
    pub deliverables: Vec<String>,
    /// How to verify the work.
    #[serde(default)]
    pub verification: Option<String>,
}

/// Resource requirements for the sandbox.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskResources {
    /// CPU cores needed (default: 2).
    #[serde(default = "default_cpu")]
    pub cpu: u32,
    /// Memory in MB (default: 4096).
    #[serde(default = "default_memory")]
    pub memory_mb: u32,
    /// GPU required?
    #[serde(default)]
    pub gpu: bool,
    /// Network access needed?
    #[serde(default = "default_network")]
    pub network: bool,
}

fn default_cpu() -> u32 {
    2
}
fn default_memory() -> u32 {
    4096
}
fn default_network() -> bool {
    true
}

impl Default for TaskResources {
    fn default() -> Self {
        Self {
            cpu: default_cpu(),
            memory_mb: default_memory(),
            gpu: false,
            network: default_network(),
        }
    }
}

/// Full task specification submitted by a supervisor.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct TaskSpec {
    /// Unique task ID (generated by supervisor).
    pub id: String,
    /// Short human-readable title.
    pub title: String,
    /// Target repository (pesti, crabjar, mirror-lab).
    pub repo: String,
    /// What the worker needs to do.
    pub context: TaskContext,
    /// Expected outcome and verification.
    pub outcome: TaskOutcome,
    /// Resource requirements.
    #[serde(default)]
    pub resources: TaskResources,
    /// Timeout in seconds (default: 3600).
    #[serde(default = "default_timeout")]
    pub timeout_seconds: u32,
    /// Container image to use for the sandbox (e.g., "rust:slim", "alpine:3.20").
    #[serde(default)]
    pub image: Option<String>,
    /// Shell command to execute inside the container. If empty, runs default validation.
    #[serde(default)]
    pub command: Option<String>,
}

fn default_timeout() -> u32 {
    3600
}

impl TaskSpec {
    /// Validate the task spec for required fields.
    pub fn validate(&self) -> Result<(), String> {
        if self.id.is_empty() {
            return Err("task id is required".to_string());
        }
        if self.title.is_empty() {
            return Err("task title is required".to_string());
        }
        if self.repo.is_empty() {
            return Err("repo is required".to_string());
        }
        if self.context.description.is_empty() {
            return Err("context.description is required".to_string());
        }
        if self.outcome.definition_of_done.is_empty() {
            return Err("outcome.definition_of_done is required".to_string());
        }
        Ok(())
    }

    /// Validate the repo against allowed values.
    pub fn validate_repo(&self) -> Result<(), String> {
        match self.repo.as_str() {
            "pesti" | "crabjar" | "mirror-lab" => Ok(()),
            other => Err(format!(
                "unknown repo '{other}'; expected 'pesti', 'crabjar', or 'mirror-lab'"
            )),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn valid_spec() -> TaskSpec {
        TaskSpec {
            id: "task-001".to_string(),
            title: "Implement feature X".to_string(),
            repo: "pesti".to_string(),
            context: TaskContext {
                description: "Add support for Y in module Z".to_string(),
                repo: Some("pesti".to_string()),
                branch: Some("main".to_string()),
                relevant_files: vec!["src/inference/mod.rs".to_string()],
                constraints: vec!["Do not change the public API".to_string()],
            },
            outcome: TaskOutcome {
                definition_of_done: "Tests pass and feature works end-to-end".to_string(),
                deliverables: vec!["Working code", "Tests"]
                    .into_iter()
                    .map(String::from)
                    .collect(),
                verification: Some("cargo test -p pesti-inference".to_string()),
            },
            resources: TaskResources {
                cpu: 4,
                memory_mb: 8192,
                gpu: false,
                network: true,
            },
            timeout_seconds: 7200,
            image: Some("rust:slim".to_string()),
            command: Some("cargo test -p pesti-inference".to_string()),
        }
    }

    #[test]
    fn valid_task_spec_passes() {
        let spec = valid_spec();
        assert!(spec.validate().is_ok());
        assert!(spec.validate_repo().is_ok());
    }

    #[test]
    fn missing_id_fails() {
        let mut spec = valid_spec();
        spec.id = "".to_string();
        assert!(spec.validate().is_err());
    }

    #[test]
    fn missing_description_fails() {
        let mut spec = valid_spec();
        spec.context.description = "".to_string();
        assert!(spec.validate().is_err());
    }

    #[test]
    fn invalid_repo_fails() {
        let mut spec = valid_spec();
        spec.repo = "unknown-repo".to_string();
        assert!(spec.validate_repo().is_err());
    }

    #[test]
    fn all_known_repos_pass() {
        for repo in ["pesti", "crabjar", "mirror-lab"] {
            let mut spec = valid_spec();
            spec.repo = repo.to_string();
            assert!(
                spec.validate_repo().is_ok(),
                "repo '{repo}' should be valid"
            );
        }
    }

    #[test]
    fn defaults_apply_when_omitted() {
        let json = r#"{
            "id": "task-002",
            "title": "Minimal spec",
            "repo": "crabjar",
            "context": {"description": "Do something"},
            "outcome": {"definition_of_done": "It works"}
        }"#;
        let spec: TaskSpec = serde_json::from_str(json).unwrap();
        assert_eq!(spec.resources.cpu, 2);
        assert_eq!(spec.resources.memory_mb, 4096);
        assert!(!spec.resources.gpu);
        assert!(spec.resources.network);
        assert_eq!(spec.timeout_seconds, 3600);
    }

    #[test]
    fn full_spec_roundtrip() {
        let spec = valid_spec();
        let json = serde_json::to_string(&spec).unwrap();
        let parsed: TaskSpec = serde_json::from_str(&json).unwrap();
        assert_eq!(parsed.id, spec.id);
        assert_eq!(parsed.repo, spec.repo);
        assert_eq!(parsed.resources.cpu, spec.resources.cpu);
        assert_eq!(parsed.image, spec.image);
        assert_eq!(parsed.command, spec.command);
    }

    #[test]
    fn image_and_command_are_optional() {
        let json = r#"{
            "id": "task-003",
            "title": "No image or command",
            "repo": "crabjar",
            "context": {"description": "Test optional fields"},
            "outcome": {"definition_of_done": "Fields default to None"}
        }"#;
        let spec: TaskSpec = serde_json::from_str(json).unwrap();
        assert!(spec.image.is_none());
        assert!(spec.command.is_none());
    }
}
